def build(root):
    errors = []
    for lang, d in L.items():
        missing = [k for k in KEYS if k not in d]
        extra = [k for k in d if k not in KEYS]
        if missing or extra:
            errors.append(f'{lang}: faltan {missing} sobran {extra}')
        if len(d['extName']) > 75: errors.append(f'{lang}: extName > 75')
        if len(d['extShortName']) > 12: errors.append(f'{lang}: extShortName > 12')
        if len(d['extDescription']) > 132: errors.append(f'{lang}: extDescription {len(d["extDescription"])} > 132')
        if '$COUNT$' not in d['messagesCount']: errors.append(f'{lang}: messagesCount sin $COUNT$')
        if d['extShortName'] not in d['step1Text']: errors.append(f'{lang}: step1Text no cita el nombre corto')
        out = {}
        for k in KEYS:
            out[k] = {'message': d[k]}
            if k == 'messagesCount':
                out[k]['placeholders'] = {'count': {'content': '$1'}}
        os.makedirs(f'{root}/{lang}', exist_ok=True)
        with open(f'{root}/{lang}/messages.json', 'w', encoding='utf-8') as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
    return errors


